// pre-rasterized offline into CELLS (not recomputed at runtime): the 20x20
// World logo path is rasterized into a 756x700 grid (8px cells, 4px gaps,
// logo drawn at 1.18x the short edge, centered; cells kept where sampled mask
// alpha >= 0.08). Each cell's opacity is maskAlpha * grain, where grain uses
// rand(i, s) = frac(sin(i * 947.173 + s * 117.31) * 10000) over the cell's
// row-major index: rand(i, 43) < 0.06 ? 0.5 : 0.78 + rand(i, 3) * 0.22.
// Opacities are quantized to 0.05 steps.
//
// Cells are individual <rect> elements (rather than merged into grouped
// <path>s) so a pointer-driven "lens" can scale the cells nearest the cursor.
// The lens writes transforms directly to the DOM via refs instead of React
// state, since re-rendering 1,645 elements per pointermove would be far more
// expensive than mutating a handful of style attributes each frame.

