// Radius and peak boost for the pointer lens, in the SVG's own 756x700
// coordinate space (8px cells, 12px pitch) so they scale with the artwork
// regardless of the rendered size.
const LENS_RADIUS = 120;
const LENS_MAX_SCALE = 3.5;
// Scaled-up cells overlap their neighbors, so their opacity is faded toward
// this fraction of its original value near the cursor - otherwise the
// overlapping dark halftone dots stack into a solid black blob.
const LENS_MIN_OPACITY_FACTOR = 0.35;
// Dimming a near-black fill via opacity alone still reads as flat charcoal
// against the light background. Interpolating the fill color itself toward
// a warm off-white as cells near the cursor gives a softer "halo" instead.
const DOT_BASE_RGB = [24, 24, 24] as const; // #181818
const DOT_LIGHT_RGB = [232, 230, 226] as const; // soft warm light gray

// A click sends a ring expanding outward from the click point across the
// dot grid over RIPPLE_DURATION_MS, reaching RIPPLE_MAX_RADIUS at the end.
// Only cells the lens/icon system isn't already actively driving are
// touched, so the ripple never fights the hover effects for the same style
// properties.
const RIPPLE_DURATION_MS = 1100;
const RIPPLE_MAX_RADIUS = 420;
const RIPPLE_BAND_WIDTH = 40;
const RIPPLE_MAX_SCALE_BOOST = 1.4;
// Icons reach full, sharp, disproportionate zoom only within this tighter
// radius (see ICON_BLUR_RADIUS below for the softer ring just beyond it) -
// cells outside both just stay zoomed halftone dots.
const ICON_REVEAL_RADIUS = 40;
// Icons get their own (steeper) falloff, scaled against ICON_REVEAL_RADIUS
// rather than the wider LENS_RADIUS, so the icon nearest the cursor pops
// disproportionately relative to ones even one cell away instead of all
// revealed icons growing at roughly the same rate.
const ICON_MAX_SCALE = 9;
const ICON_FALLOFF_POWER = 3;
// A modest ring just beyond ICON_REVEAL_RADIUS: icons there fetch/reveal at
// rest size but blurred, coming into focus as the cursor approaches, instead
// of popping in sharp from nothing. Kept narrow and lightly blurred on
// purpose - this is decoration, not the interaction focus, so it shouldn't
// meaningfully add to the icon-fetch count or per-frame filter cost.
const ICON_BLUR_RADIUS = 60;
const ICON_MAX_BLUR = 3;
const ICON_RING_MIN_OPACITY = 0.35;
// Cell width/height in the source grid (see CELLS above).
const CELL_SIZE = 8;

// Clicking an icon compresses it (like a physical button) over
// PRESS_COMPRESS_DURATION_MS, then springs back past its normal size before
// settling, over PRESS_RELEASE_DURATION_MS. This is layered as a multiplier
// on top of whatever scale the lens/reveal system already computed for that
// icon that frame, rather than replacing it.
const PRESS_COMPRESS_SCALE = 0.8;
const PRESS_COMPRESS_DURATION_MS = 120;
const PRESS_RELEASE_DURATION_MS = 380;

const easeOutCubic = (t: number) => 1 - (1 - t) ** 3;

// "Back ease": overshoots past 1 before settling, which is what reads as a
// spring bounce rather than a plain ease-out.
const easeOutBack = (t: number) => {
  const c1 = 1.70158;
  const c3 = c1 + 1;
  return 1 + c3 * (t - 1) ** 3 + c1 * (t - 1) ** 2;
};

// A loader Image with no other reference can be garbage-collected mid-flight
// - the request gets silently cancelled and onload/onerror never fires. Keep
// every in-flight image alive here until it settles.
const pendingIconImages = new Set<HTMLImageElement>();

// Resolves once the browser has actually fetched/decoded the image, so this
// behaves like real <img> loading and caching (repeat calls with the same
// href resolve instantly) rather than assuming the icon is already there.
const loadImage = (href: string) =>
  new Promise<void>((resolve, reject) => {
    const image = new Image();
    pendingIconImages.add(image);

    const settle = (run: () => void) => {
      pendingIconImages.delete(image);
      run();
    };

    image.onload = () => settle(resolve);
    image.onerror = () =>
      settle(() => reject(new Error(`Failed to load icon: ${href}`)));
    image.src = href;
  });

export const BasePixelStrip = () => {
  const svgRef = useRef<SVGSVGElement>(null);
  const rectsRef = useRef<Map<string, SVGRectElement>>(new Map());
  const activeRef = useRef<Set<string>>(new Set());
  const pointerRef = useRef<{ x: number; y: number } | null>(null);
  const frameRef = useRef<number | null>(null);
  const iconElsRef = useRef<Map<string, SVGImageElement>>(new Map());
  const iconHrefCacheRef = useRef<Map<number, string>>(new Map());
  const iconLoadingRef = useRef<Set<number>>(new Set());
  const revealedRef = useRef<Set<string>>(new Set());
  const ripplesRef = useRef<Array<{ x: number; y: number; start: number }>>([]);
  const rippleActiveRef = useRef<Set<string>>(new Set());
  const pressRef = useRef<{
    key: string;
    phase: "compress" | "release";
    start: number;
  } | null>(null);

  useEffect(() => {
    const svg = svgRef.current;

    if (!svg) {
      return;
    }

    // Skip the lens for touch/reduced-motion contexts: there's no hover to
    // drive it, and constant contact would just make it fire under a finger.
    const supportsHover = window.matchMedia(
      "(hover: hover) and (pointer: fine)",
    ).matches;
    const prefersReducedMotion = window.matchMedia(
      "(prefers-reduced-motion: reduce)",
    ).matches;

    if (!supportsHover || prefersReducedMotion) {
      return;
    }

    const toSvgPoint = (clientX: number, clientY: number) => {
      const ctm = svg.getScreenCTM();

      if (!ctm) {
        return null;
      }

      const point = svg.createSVGPoint();
      point.x = clientX;
      point.y = clientY;

      const transformed = point.matrixTransform(ctm.inverse());
      return { x: transformed.x, y: transformed.y };
    };

    const getOrCreateIconEl = (key: string, x: number, y: number) => {
      let image = iconElsRef.current.get(key);

      if (!image) {
        image = document.createElementNS("http://www.w3.org/2000/svg", "image");
        image.setAttribute("class", "pixel-icon");
        image.setAttribute("x", String(x));
        image.setAttribute("y", String(y));
        image.setAttribute("width", "8");
        image.setAttribute("height", "8");
        svg.appendChild(image);
        iconElsRef.current.set(key, image);
      }

      return image;
    };

    const applyLens = () => {
      frameRef.current = null;

      const now = performance.now();
      const pointer = pointerRef.current;
      const nextActive = new Set<string>();
      const revealedIcons: Array<{ image: SVGImageElement; scale: number }> =
        [];

      // The press spring only ever targets one specific cell (fixed at
      // pointerdown time), so its multiplier is computed once per frame
      // rather than per cell.
      let pressKey: string | null = null;
      let pressMultiplier = 1;

      if (pressRef.current) {
        const press = pressRef.current;
        const elapsed = now - press.start;

        if (press.phase === "compress") {
          const t = Math.min(1, elapsed / PRESS_COMPRESS_DURATION_MS);
          pressMultiplier = 1 - (1 - PRESS_COMPRESS_SCALE) * easeOutCubic(t);
        } else {
          const t = Math.min(1, elapsed / PRESS_RELEASE_DURATION_MS);
          pressMultiplier =
            PRESS_COMPRESS_SCALE + (1 - PRESS_COMPRESS_SCALE) * easeOutBack(t);

          if (t >= 1) {
            pressRef.current = null;
          }
        }

        pressKey = press.key;
      }

      if (pointer) {
        for (let i = 0; i < CELLS.length; i++) {
          const [x, y, opacity] = CELLS[i];
          const dx = x + 4 - pointer.x;
          const dy = y + 4 - pointer.y;
          const dist = Math.sqrt(dx * dx + dy * dy);

          if (dist >= LENS_RADIUS) {
            continue;
          }

          const key = `${x},${y}`;
          const falloff = 1 - dist / LENS_RADIUS;
          const scale = 1 + LENS_MAX_SCALE * falloff * falloff;
          const opacityFactor = 1 - falloff * (1 - LENS_MIN_OPACITY_FACTOR);
          const rect = rectsRef.current.get(key);

          if (rect) {
            rect.style.transform = `scale(${scale.toFixed(3)})`;
            rect.style.fillOpacity = `${(opacity * opacityFactor).toFixed(3)}`;

            const dotR = Math.round(
              DOT_BASE_RGB[0] + (DOT_LIGHT_RGB[0] - DOT_BASE_RGB[0]) * falloff,
            );
            const dotG = Math.round(
              DOT_BASE_RGB[1] + (DOT_LIGHT_RGB[1] - DOT_BASE_RGB[1]) * falloff,
            );
            const dotB = Math.round(
              DOT_BASE_RGB[2] + (DOT_LIGHT_RGB[2] - DOT_BASE_RGB[2]) * falloff,
            );
            rect.style.fill = `rgb(${dotR}, ${dotG}, ${dotB})`;

            // Scaled-up cells overlap their neighbors; repaint them last (on
            // top) the moment they become active so the zoom reads cleanly
            // instead of getting clipped under a later, unscaled sibling.
            if (!activeRef.current.has(key)) {
              rect.parentNode?.appendChild(rect);
            }
          }

          // Only cells within the blur ring "develop" into icons - lazily
          // fetching just those keeps this cheap (no upfront requests for
          // all 1,645 cells) and matches the lens metaphor: you reveal an
          // icon by approaching it, not before.
          if (dist < ICON_BLUR_RADIUS) {
            const cachedHref = iconHrefCacheRef.current.get(i);

            if (cachedHref) {
              const image = getOrCreateIconEl(key, x, y);

              if (image.getAttribute("href") !== cachedHref) {
                image.setAttribute("href", cachedHref);
              }

              if (dist < ICON_REVEAL_RADIUS) {
                const iconFalloff = 1 - dist / ICON_REVEAL_RADIUS;
                const baseIconScale =
                  1 + ICON_MAX_SCALE * iconFalloff ** ICON_FALLOFF_POWER;
                // The press spring is layered on top of the lens's own
                // scale for whichever one cell is currently pressed - it
                // doesn't replace it.
                const iconScale =
                  key === pressKey
                    ? baseIconScale * pressMultiplier
                    : baseIconScale;
                // A quarter of the icon's current on-screen size - enough
                // that the pointer doesn't fully cover it, while still
                // overlapping it rather than sitting at its edge.
                const iconOffset = (CELL_SIZE * iconScale) / 4;

                image.style.transform = `translate(${iconOffset.toFixed(3)}px, ${(-iconOffset).toFixed(3)}px) scale(${iconScale.toFixed(3)})`;
                image.style.opacity = "1";
                image.style.filter = "";

                // Defer stacking: the most-zoomed icon must always paint on
                // top, and which icon that is changes every frame as the
                // cursor moves - so z-order is resolved once below, by
                // current scale, rather than by activation order here.
                revealedIcons.push({ image, scale: iconScale });
              } else {
                // The blur ring: icons here sit at rest size, blurred and
                // partly faded, sharpening into full focus as the cursor
                // gets closer instead of popping in abruptly.
                const ringT =
                  (dist - ICON_REVEAL_RADIUS) /
                  (ICON_BLUR_RADIUS - ICON_REVEAL_RADIUS);

                image.style.transform = "";
                image.style.opacity = (
                  1 -
                  ringT * (1 - ICON_RING_MIN_OPACITY)
                ).toFixed(3);
                image.style.filter = `blur(${(ICON_MAX_BLUR * ringT).toFixed(2)}px)`;
              }

              if (rect) {
                // Fade the underlying halftone dot out so the icon reads
                // clearly once it's revealed.
                rect.style.fillOpacity = `${(opacity * opacityFactor * 0.15).toFixed(3)}`;
              }

              // Once shown, an icon stays part of the grid permanently -
              // it doesn't revert to the halftone dot when the cursor
              // moves away.
              revealedRef.current.add(key);
            } else if (
              !iconLoadingRef.current.has(i) &&
              !iconHrefCacheRef.current.has(i)
            ) {
              iconLoadingRef.current.add(i);
              const href = ICON_SOURCES[i];

              loadImage(href)
                .then(() => {
                  iconHrefCacheRef.current.set(i, href);
                })
                .catch(() => {
                  // No icon overlay for this cell; the halftone dot alone
                  // still reads fine.
                })
                .finally(() => {
                  iconLoadingRef.current.delete(i);
                  scheduleFrame();
                });
            }
          } else if (revealedRef.current.has(key)) {
            // Outside the blur ring but already revealed earlier - settle
            // at rest (no zoom, no blur, no cursor-avoidance offset) rather
            // than hiding it again.
            const image = iconElsRef.current.get(key);

            if (image) {
              image.style.transform = "";
              image.style.opacity = "1";
              image.style.filter = "";
            }

            if (rect) {
              rect.style.fillOpacity = `${(opacity * opacityFactor * 0.15).toFixed(3)}`;
            }
          } else {
            const image = iconElsRef.current.get(key);

            if (image) {
              image.style.opacity = "0";
            }
          }

          nextActive.add(key);
        }
      }

      // Repaint every revealed icon last (in ascending scale order), so the
      // most-zoomed one ends up as the final child and always renders on
      // top - not just whichever cell happened to activate most recently.
      revealedIcons.sort((a, b) => a.scale - b.scale);

      for (const { image } of revealedIcons) {
        image.parentNode?.appendChild(image);
      }

      for (const key of activeRef.current) {
        if (!nextActive.has(key)) {
          const rect = rectsRef.current.get(key);
          const image = iconElsRef.current.get(key);
          const revealed = revealedRef.current.has(key);

          if (rect) {
            rect.style.transform = "";
            // A revealed cell's dot stays dimmed permanently (see above) -
            // only reset it here if the icon never actually loaded.
            rect.style.fillOpacity = revealed ? rect.style.fillOpacity : "";
            rect.style.fill = revealed ? rect.style.fill : "";
          }

          if (image) {
            image.style.transform = "";
            image.style.opacity = revealed ? "1" : "0";
            image.style.filter = "";
          }
        }
      }

      activeRef.current = nextActive;

      // Ripple pass: independent of the lens/hover state above, and only
      // touches cells neither the lens nor a settled icon reveal already
      // owns, so it never clobbers those effects.
      ripplesRef.current = ripplesRef.current.filter(
        (ripple) => now - ripple.start < RIPPLE_DURATION_MS,
      );

      if (ripplesRef.current.length > 0 || rippleActiveRef.current.size > 0) {
        const nextRippleActive = new Set<string>();

        for (let i = 0; i < CELLS.length; i++) {
          const [x, y, opacity] = CELLS[i];
          const key = `${x},${y}`;

          if (activeRef.current.has(key) || revealedRef.current.has(key)) {
            continue;
          }

          let intensity = 0;

          for (const ripple of ripplesRef.current) {
            const progress = (now - ripple.start) / RIPPLE_DURATION_MS;
            const currentRadius = progress * RIPPLE_MAX_RADIUS;
            const dx = x + 4 - ripple.x;
            const dy = y + 4 - ripple.y;
            const cellDist = Math.sqrt(dx * dx + dy * dy);
            const bandDist = Math.abs(cellDist - currentRadius);

            if (bandDist >= RIPPLE_BAND_WIDTH) {
              continue;
            }

            const bandFalloff = 1 - bandDist / RIPPLE_BAND_WIDTH;
            const envelope = 1 - progress;
            intensity = Math.max(intensity, bandFalloff * envelope);
          }

          const rect = rectsRef.current.get(key);

          if (intensity > 0.02) {
            if (rect) {
              const rippleScale = 1 + RIPPLE_MAX_SCALE_BOOST * intensity;
              rect.style.transform = `scale(${rippleScale.toFixed(3)})`;
              rect.style.fillOpacity = `${Math.min(1, opacity + intensity * 0.3).toFixed(3)}`;

              const rippleR = Math.round(
                DOT_BASE_RGB[0] +
                  (DOT_LIGHT_RGB[0] - DOT_BASE_RGB[0]) * intensity,
              );
              const rippleG = Math.round(
                DOT_BASE_RGB[1] +
                  (DOT_LIGHT_RGB[1] - DOT_BASE_RGB[1]) * intensity,
              );
              const rippleB = Math.round(
                DOT_BASE_RGB[2] +
                  (DOT_LIGHT_RGB[2] - DOT_BASE_RGB[2]) * intensity,
              );
              rect.style.fill = `rgb(${rippleR}, ${rippleG}, ${rippleB})`;

              // Newly rippling cells repaint last so the wavefront isn't
              // clipped under a neighbor it hasn't reached yet.
              if (!rippleActiveRef.current.has(key)) {
                rect.parentNode?.appendChild(rect);
              }
            }

            nextRippleActive.add(key);
          } else if (rippleActiveRef.current.has(key) && rect) {
            rect.style.transform = "";
            rect.style.fillOpacity = "";
            rect.style.fill = "";
          }
        }

        rippleActiveRef.current = nextRippleActive;
      }

      if (ripplesRef.current.length > 0 || pressRef.current) {
        scheduleFrame();
      }
    };

    const scheduleFrame = () => {
      if (frameRef.current === null) {
        frameRef.current = requestAnimationFrame(applyLens);
      }
    };

    // The pressed cell is fixed at pointerdown time (the nearest icon
    // currently in full sharp focus) and the spring plays out on that one
    // cell regardless of where the pointer moves before release.
    const findPressedIconKey = (point: { x: number; y: number }) => {
      let bestKey: string | null = null;
      let bestDist = Infinity;

      for (let i = 0; i < CELLS.length; i++) {
        if (!iconHrefCacheRef.current.has(i)) {
          continue;
        }

        const [x, y] = CELLS[i];
        const dx = x + 4 - point.x;
        const dy = y + 4 - point.y;
        const dist = Math.sqrt(dx * dx + dy * dy);

        if (dist < ICON_REVEAL_RADIUS && dist < bestDist) {
          bestDist = dist;
          bestKey = `${x},${y}`;
        }
      }

      return bestKey;
    };

    const handlePointerMove = (event: PointerEvent) => {
      pointerRef.current = toSvgPoint(event.clientX, event.clientY);
      scheduleFrame();
    };

    const handlePointerLeave = () => {
      pointerRef.current = null;

      // Don't leave the icon stuck mid-compress if the pointer leaves
      // before releasing.
      if (pressRef.current?.phase === "compress") {
        pressRef.current = {
          ...pressRef.current,
          phase: "release",
          start: performance.now(),
        };
      }

      scheduleFrame();
    };

    const handlePointerDown = (event: PointerEvent) => {
      const point = toSvgPoint(event.clientX, event.clientY);

      if (!point) {
        return;
      }

      const key = findPressedIconKey(point);

      if (!key) {
        return;
      }

      pressRef.current = { key, phase: "compress", start: performance.now() };
      scheduleFrame();
    };

    const handlePointerUp = () => {
      if (pressRef.current?.phase === "compress") {
        pressRef.current = {
          ...pressRef.current,
          phase: "release",
          start: performance.now(),
        };
        scheduleFrame();
      }
    };

    const handleClick = (event: MouseEvent) => {
      const point = toSvgPoint(event.clientX, event.clientY);

      if (!point) {
        return;
      }

      ripplesRef.current.push({ ...point, start: performance.now() });
      scheduleFrame();
    };

    svg.addEventListener("pointermove", handlePointerMove);
    svg.addEventListener("pointerleave", handlePointerLeave);
    svg.addEventListener("pointerdown", handlePointerDown);
    svg.addEventListener("pointerup", handlePointerUp);
    svg.addEventListener("click", handleClick);

    return () => {
      svg.removeEventListener("pointermove", handlePointerMove);
      svg.removeEventListener("pointerleave", handlePointerLeave);
      svg.removeEventListener("pointerdown", handlePointerDown);
      svg.removeEventListener("pointerup", handlePointerUp);
      svg.removeEventListener("click", handleClick);

      if (frameRef.current !== null) {
        cancelAnimationFrame(frameRef.current);
      }
    };
  }, []);

  return (
    <section
      aria-label="World logomark pixel field"
      className="absolute inset-0 bg-[#f9f9f8]"
    >
      <style dangerouslySetInnerHTML={{ __html: FADE_IN_STYLE }} />

      <svg
        aria-hidden="true"
        className="base-pixel-mark size-full"
        fill="none"
        ref={svgRef}
        viewBox="0 0 756 700"
        xmlns="http://www.w3.org/2000/svg"
      >
        <defs>
          {/* objectBoundingBox so one definition rounds every icon's
              corners regardless of its own x/y/width or current zoom. */}
          <clipPath clipPathUnits="objectBoundingBox" id="pixel-icon-clip">
            <rect height="1" rx="0.22" ry="0.22" width="1" x="0" y="0" />
          </clipPath>
        </defs>

        {CELLS.map(([x, y, opacity]) => (
          <rect
            className="pixel-cell"
            fill="#181818"
            fillOpacity={opacity}
            height={8}
            key={`${x}-${y}`}
            ref={(node) => {
              const key = `${x},${y}`;

              if (node) {
                rectsRef.current.set(key, node);
              } else {
                rectsRef.current.delete(key);
              }
            }}
            width={8}
            x={x}
            y={y}
          />
        ))}
      </svg>
    </section>
  );
};
